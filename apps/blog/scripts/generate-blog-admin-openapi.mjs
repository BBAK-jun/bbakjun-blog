import fs from 'node:fs/promises';
import path from 'node:path';

import openapiTS, { astToString } from 'openapi-typescript';
import { openApiSpec } from 'blog-admin/contract';

const outputFile = path.join(
  process.cwd(),
  'src',
  'generated',
  'blog-admin-openapi.ts'
);

const banner = `/* This file is generated by apps/blog/scripts/generate-blog-admin-openapi.mjs */\n`;

const result = await openapiTS(openApiSpec, {
  alphabetize: true,
});
const types = typeof result === 'string' ? result : astToString(result);

await fs.mkdir(path.dirname(outputFile), { recursive: true });
await fs.writeFile(outputFile, `${banner}\n${types}`, 'utf8');

console.log(`Generated: ${outputFile}`);
